#!/usr/bin/env python3
"""Render the reviewed RBAC/PBAC catalog as a Markdown matrix.

The source of truth is ``platform/backend/app/security/permissions.yaml``.
Run this after a catalog review:

    python scripts/generate-rbac-matrix.py           # write the doc
    python scripts/generate-rbac-matrix.py --check   # fail if the doc drifted

The Security Center renders the same data from the live RBAC tables; this file
is the reviewable snapshot for pull requests and auditors.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "platform/backend/app/security/permissions.yaml"
DEFAULT_OUTPUT = ROOT / "docs/RBAC-PBAC-MATRIX.md"


def _load_policy_rules() -> list[dict]:
    sys.path.insert(0, str(ROOT / "platform/backend"))
    from app.security.policy_rules import POLICY_RULES

    return list(POLICY_RULES)


def _cell(value: bool) -> str:
    return "✓" if value else ""


def render() -> str:
    document = yaml.safe_load(CATALOG.read_text(encoding="utf-8")) or {}
    roles = document.get("roles") or {}
    permissions = document.get("permissions") or {}
    policy_rules = _load_policy_rules()

    role_keys = sorted(roles, key=lambda key: (int(roles[key].get("rank") or 0), key))
    permission_keys = sorted(
        permissions,
        key=lambda key: (str(permissions[key].get("category") or ""), key),
    )

    lines: list[str] = [
        "# RBAC and PBAC matrix",
        "",
        "<!-- Generated by scripts/generate-rbac-matrix.py. Do not edit by hand. -->",
        "",
        "Source of truth: `platform/backend/app/security/permissions.yaml`.",
        "The Security Center renders the same matrix from the live RBAC tables, so an",
        "administrator's reviewed grant edits appear there immediately. This file is the",
        "reviewable snapshot for pull requests and auditors.",
        "",
        "## How to read it",
        "",
        "- **RBAC** answers *what kind of work may this role do?* The table shows the",
        "  reviewed baseline grants. A stored administrator edit can change them.",
        "- **PBAC** answers *may this actor do it to this record, in this tenant, with",
        "  this learner's consent?* A role grant is necessary but not sufficient.",
        "- `✓` means the role has the permission in the reviewed baseline. A blank cell",
        "  means the role must obtain the permission another way: owner scope, a verified",
        "  share, a course assignment, or a break-glass grant.",
        "- A permission marked `restricted` is never granted to a role. It requires the",
        "  record owner, a live share, or a time-bound break-glass grant.",
        "",
        "## Role summary",
        "",
        "| Role | Label | Rank | Grants | Tenant scope | Description |",
        "|---|---|---:|---:|---|---|",
    ]

    for key in role_keys:
        role = roles[key]
        grants = role.get("permissions") or []
        lines.append(
            "| `{}` | {} | {} | {} | `{}` | {} |".format(
                key,
                role.get("label") or key,
                role.get("rank") or 0,
                len(grants),
                role.get("tenant_scope") or "institution",
                role.get("description") or "",
            )
        )

    lines.extend(
        [
            "",
            "## RBAC permission matrix",
            "",
            "Rows are permissions, grouped by category. Columns are the reviewed roles.",
            "",
            "| Permission | " + " | ".join(f"`{key}`" for key in role_keys) + " |",
            "|---|" + "|".join(":---:" for _ in role_keys) + "|",
        ]
    )

    last_category = None
    for key in permission_keys:
        meta = permissions[key]
        category = str(meta.get("category") or "")
        if category != last_category:
            lines.append(
                "| **{}** | {} |".format(
                    category.title() or "Other",
                    " | ".join("" for _ in role_keys),
                )
            )
            last_category = category
        cells = [
            _cell(key in (roles[role].get("permissions") or [])) for role in role_keys
        ]
        lines.append(f"| `{key}` | " + " | ".join(cells) + " |")

    lines.extend(
        [
            "",
            "## PBAC attributes",
            "",
            "| Permission | Scope | Sensitivity | Read-only | Break-glass | Granted to |",
            "|---|---|---|---|---|---|",
        ]
    )

    for key in permission_keys:
        meta = permissions[key]
        granted_to = [
            role
            for role in role_keys
            if key in (roles[role].get("permissions") or [])
        ]
        lines.append(
            "| `{}` | `{}` | `{}` | {} | {} | {} |".format(
                key,
                meta.get("scope") or "global",
                meta.get("sensitivity") or "unknown",
                "yes" if meta.get("read_only") else "no",
                "yes" if meta.get("break_glass") else "no",
                ", ".join(f"`{role}`" for role in granted_to) or "— (private)",
            )
        )

    lines.extend(
        [
            "",
            "## PBAC policy rules",
            "",
            "| Rule | What it decides | Enforced by |",
            "|---|---|---|",
        ]
    )
    for rule in policy_rules:
        lines.append(
            "| **{}** | {} | `{}` |".format(
                rule.get("label") or rule.get("id") or "",
                rule.get("rule") or "",
                rule.get("enforced_by") or "",
            )
        )

    lines.extend(
        [
            "",
            "## Review checklist",
            "",
            "- [ ] Every new permission has a description, category, sensitivity, scope,",
            "      read-only flag, and break-glass flag.",
            "- [ ] Every permission is granted to at least one role, unless it is deliberately",
            "      private and requires owner, share, or break-glass access.",
            "- [ ] `admin` has no restricted permission.",
            "- [ ] `auditor` receives read-only permissions only.",
            "- [ ] Tenant scope is `global` only for `admin`, `explicit` only for",
            "      `service_account`, and `shared` only for external share roles.",
            "- [ ] The generated matrix is current (`python scripts/generate-rbac-matrix.py --check`).",
            "",
        ]
    )

    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=str(DEFAULT_OUTPUT))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    output = Path(args.output).resolve()
    rendered = render()
    if args.check:
        current = output.read_text(encoding="utf-8") if output.exists() else ""
        if current != rendered:
            print(
                f"RBAC/PBAC matrix is stale: {output}. "
                "Run `python scripts/generate-rbac-matrix.py`.",
                file=sys.stderr,
            )
            return 1
        print(f"RBAC/PBAC matrix is current: {output}")
        return 0

    output.write_text(rendered, encoding="utf-8", newline="\n")
    print(f"Wrote {output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
