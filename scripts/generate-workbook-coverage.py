"""Generate Workbook/COVERAGE.md from lab metadata.

The hand-written workbook index stays curated. This generated page is the
source of truth for which labs actually expose a workbook and how many labs per
track are covered, so stale counts and missing workbook links are caught in CI.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
LABS = ROOT / "platform" / "labs"
OUT = ROOT / "Workbook" / "COVERAGE.md"

rows = []
for lab_yaml in sorted(LABS.rglob("lab.yaml")):
    try:
        data = yaml.safe_load(lab_yaml.read_text(encoding="utf-8")) or {}
    except Exception as exc:
        print(f"warning: could not parse {lab_yaml}: {exc}", file=sys.stderr)
        continue
    workbook = str(data.get("workbook") or "").strip()
    if not workbook:
        continue
    track = lab_yaml.parent.parent.name
    lab_name = str(data.get("title") or data.get("name") or lab_yaml.parent.name).strip()
    rows.append((track, lab_name, lab_yaml.parent.name, workbook))

by_track = defaultdict(list)
for track, lab_name, slug, workbook in rows:
    by_track[track].append((lab_name, slug, workbook))

lines = [
    "# Workbook coverage",
    "",
    "Generated from `platform/labs/**/lab.yaml`. Do not edit this file by hand;",
    "run `python scripts/generate-workbook-coverage.py` after changing workbook",
    "links.",
    "",
    "| Track | Labs with workbook |",
    "|---|---:|",
]
for track in sorted(by_track):
    lines.append(f"| {track} | {len(by_track[track])} |")
lines.append(f"| **Total** | **{len(rows)}** |")
lines.extend(["", "## Labs", "", "| Track | Lab | Workbook |", "|---|---|---|"])
for track in sorted(by_track):
    for lab_name, slug, workbook in sorted(by_track[track]):
        lines.append(f"| {track} | {lab_name} (`{slug}`) | `{workbook}` |")

content = "\n".join(lines) + "\n"

if "--check" in sys.argv:
    if not OUT.exists():
        print(f"FAIL: {OUT.relative_to(ROOT)} is missing; run the generator")
        sys.exit(1)
    if OUT.read_text(encoding="utf-8") != content:
        print(f"FAIL: {OUT.relative_to(ROOT)} is stale; run the generator")
        sys.exit(1)
    print(f"PASS: {OUT.relative_to(ROOT)} matches lab metadata")
    sys.exit(0)

OUT.write_text(content, encoding="utf-8")
print(f"wrote {OUT.relative_to(ROOT)} ({len(rows)} labs with workbooks)")
