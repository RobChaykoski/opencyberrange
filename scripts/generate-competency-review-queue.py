#!/usr/bin/env python3
"""Build the Release 6 competency-contract review queue.

The contracts file already maps every lab to competencies. Most are
baseline-derived and have not had subject-matter review. This script produces a
reviewable queue grouped by track, public labs first, with the current contract
summary and empty reviewer fields.

Usage:
    python scripts/generate-competency-review-queue.py
    python scripts/generate-competency-review-queue.py --check
    python scripts/generate-competency-review-queue.py --json docs/competency-review-queue.json
"""

from __future__ import annotations

import argparse
import json
from collections import Counter, defaultdict
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CONTRACTS = ROOT / "platform/backend/app/data/competency-contracts.yaml"
LABS = ROOT / "platform/labs"
OUTPUT = ROOT / "docs/COMPETENCY-REVIEW-QUEUE.md"
REVIEWED = "reviewed"


def load_yaml(path: Path) -> dict:
    with path.open(encoding="utf-8") as handle:
        return yaml.safe_load(handle) or {}


def lab_metadata() -> dict[str, dict]:
    result: dict[str, dict] = {}
    for path in LABS.rglob("lab.yaml"):
        data = load_yaml(path)
        result[path.parent.name] = {
            "title": str(data.get("title") or path.parent.name),
            "difficulty": str(data.get("difficulty") or "unknown"),
            "visibility": str(data.get("visibility") or "public"),
            "minutes": data.get("estimated_time"),
            "track": path.relative_to(LABS).parts[0],
        }
    return result


def cell(value: object) -> str:
    return str(value or "").replace("|", "\\|").replace("\n", " ").strip()


def build() -> tuple[str, dict]:
    contracts = load_yaml(CONTRACTS).get("labs") or {}
    metadata = lab_metadata()
    pending: list[dict] = []

    for slug, contract in contracts.items():
        if not isinstance(contract, dict):
            continue
        if str(contract.get("review_status")) == REVIEWED:
            continue
        lab = metadata.get(slug, {})
        competencies = contract.get("competency_ids") or []
        evidence = contract.get("evidence") or []
        pending.append(
            {
                "slug": slug,
                "title": lab.get("title", slug),
                "track": lab.get("track", contract.get("track", "Unknown")),
                "difficulty": lab.get("difficulty", contract.get("difficulty", "unknown")),
                "visibility": lab.get("visibility", "public"),
                "minutes": lab.get("minutes"),
                "competencies": [
                    item.get("id") for item in competencies if isinstance(item, dict) and item.get("id")
                ],
                "evidence": [item.get("type") for item in evidence if isinstance(item, dict) and item.get("type")],
                "review_status": contract.get("review_status"),
            }
        )

    pending.sort(key=lambda row: (row["track"].lower(), row["visibility"] != "public", row["slug"]))
    total = len(contracts)
    reviewed = total - len(pending)
    by_track = Counter(row["track"] for row in pending)
    by_status = Counter(str(row["review_status"] or "unknown") for row in pending)

    lines = [
        "# Competency-contract review queue",
        "",
        "Generated by `scripts/generate-competency-review-queue.py`. Do not edit by hand.",
        "",
        "Release 6.0 requires a reviewed contract for every lab. This page lists the",
        "contracts that are still baseline-derived. Review the competencies and evidence",
        "weights against the exercise, then change `review_status` to `reviewed` in",
        "`platform/backend/app/data/competency-contracts.yaml` and regenerate the",
        "contracts and this queue.",
        "",
        "## Summary",
        "",
        "| Measure | Value |",
        "|---|---:|",
        f"| Contracts | **{total}** |",
        f"| Reviewed | **{reviewed}** |",
        f"| Awaiting review | **{len(pending)}** |",
        f"| Review coverage | **{(reviewed / total * 100) if total else 0:.1f}%** |",
        "",
        "| Track | Awaiting review |",
        "|---|---:|",
    ]
    for track, count in sorted(by_track.items()):
        lines.append(f"| {cell(track)} | {count} |")

    lines.extend(
        [
            "",
            "| Contract status | Count |",
            "|---|---:|",
        ]
    )
    for status, count in sorted(by_status.items()):
        lines.append(f"| `{cell(status)}` | {count} |")

    lines.extend(
        [
            "",
            "## Review queue",
            "",
            "Public labs are listed first within each track. Fill the reviewer, decision,",
            "and date columns in the review record, not in this generated page.",
            "",
            "| Lab | Track | Difficulty | Visibility | Minutes | Competencies | Evidence | Status |",
            "|---|---|---|---|---:|---|---|---|",
        ]
    )
    for row in pending:
        lines.append(
            "| `{slug}` {title} | {track} | {difficulty} | {visibility} | {minutes} | {competencies} | {evidence} | {status} |".format(
                slug=cell(row["slug"]),
                title=cell(row["title"]),
                track=cell(row["track"]),
                difficulty=cell(row["difficulty"]),
                visibility=cell(row["visibility"]),
                minutes=cell(row["minutes"] or ""),
                competencies=", ".join(cell(item) for item in row["competencies"]) or "none",
                evidence=", ".join(cell(item) for item in row["evidence"]) or "none",
                status=cell(row["review_status"]),
            )
        )

    lines.extend(
        [
            "",
            "## Review rule",
            "",
            "A contract is reviewed only when a subject-matter reviewer has checked:",
            "",
            "- every competency id exists in the taxonomy;",
            "- the evidence types can actually be produced by the exercise;",
            "- the weights sum to 1.0;",
            "- the evidence is observable in the platform, not implied;",
            "- the difficulty and prerequisites match the workout;",
            "- the review has a named reviewer and a date.",
            "",
            "The generated contract file is not the review record. Keep the reviewer",
            "name and decision in the change that flips the status.",
            "",
            "## Validate before review",
            "",
            "```bash",
            "python scripts/validate-competency-contracts.py",
            "python scripts/validate-competency-contracts.py --json",
            "```",
            "",
            "The validator checks every competency id against the taxonomy, every weight",
            "sum, the evidence types, and the one-contract-per-lab rule. It does not judge",
            "whether the competency is the right one; that is the reviewer's decision.",
            "",
            "## Regenerate",
            "",
            "```bash",
            "python scripts/generate-competency-review-queue.py",
            "python scripts/generate-competency-review-queue.py --check",
            "```",
            "",
        ]
    )

    payload = {
        "total": total,
        "reviewed": reviewed,
        "pending": len(pending),
        "by_track": dict(sorted(by_track.items())),
        "labs": pending,
    }
    return "\n".join(lines), payload


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Fail if the generated page is stale")
    parser.add_argument("--json", type=Path, help="Also write the machine-readable queue")
    args = parser.parse_args()

    content, payload = build()

    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            print(f"FAIL: {OUTPUT.relative_to(ROOT)} is stale; run the generator", flush=True)
            return 1
        print(f"PASS: {OUTPUT.relative_to(ROOT)} is current ({payload['pending']} awaiting review)")
        return 0

    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Wrote {OUTPUT.relative_to(ROOT)} ({payload['pending']} awaiting review)")
    if args.json:
        args.json.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        print(f"Wrote {args.json}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
